import TelegramBot from "node-telegram-bot-api";
import dotenv from "dotenv";
import { saveDraft } from "../src/drafts";
import { loadProfile } from "../src/profile";
import { getPersona, buildSenderSignature } from "../src/data/candidatePersonas";

dotenv.config();

// Sends a demo job alert to your own Telegram chat. The draft's recipient is
// your own GMAIL_USER, so tapping "Send" only emails yourself.

const bot = new TelegramBot(process.env.TELEGRAM_BOT_TOKEN!, { polling: false });
const chatId = process.env.TELEGRAM_CHAT_ID!;
const jobId = "test_demo_01";

async function main() {
  const profile = loadProfile();
  const persona = getPersona(profile, profile.defaultPersona);

  saveDraft({
    jobId,
    jobTitle: "Founding Engineer (Demo Test)",
    company: "Example Corp",
    recipientEmail: process.env.GMAIL_USER!,
    recipientName: "Alex Example",
    draftEmail: `Hi Alex,

I saw the Founding Engineer role at Example Corp and wanted to connect directly. This is a demo draft generated by the test-alert script.

${buildSenderSignature(profile, persona)}`,
    subject: persona.buildSubject("Founding Engineer (Demo Test)"),
    url: "https://remoteok.com",
    createdAt: new Date().toISOString(),
    status: "pending",
    track: persona.key,
    resumeFilename: persona.resume,
  });

  const message =
`🏢 *Founding Engineer \\(Demo Test\\) — Example Corp*

🔗 [Apply Here](https://remoteok.com)

🔑 *Matched Keywords:* founding engineer, typescript

👤 *Decision Maker:*
   Name: Alex Example
   Title: Founder
   Email: \`${process.env.GMAIL_USER}\`

✉️ *Personalized Draft Email:*
Hi Alex\\,
I saw the Founding Engineer role at Example Corp\\.\\.\\.

👇 *Try tapping one of the buttons below:*`;

  await bot.sendMessage(chatId, message, {
    parse_mode: "MarkdownV2",
    reply_markup: {
      inline_keyboard: [
        [
          { text: "✉️ Send Test Email", callback_data: `send:${jobId}` },
          { text: "✏️ Edit Draft", callback_data: `edit:${jobId}` },
          { text: "❌ Skip", callback_data: `skip:${jobId}` },
        ],
      ],
    },
  });

  console.log("DEMO_ALERT_SENT_SUCCESSFULLY");
}

main().catch(console.error);
